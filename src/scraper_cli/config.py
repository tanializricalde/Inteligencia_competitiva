def _table(value: Any, location: str) -> dict[str, Any]:
    if not isinstance(value, dict):
        raise ConfigError(f"{location}: debe ser una tabla TOML")
    return value


def _reject_unknown(data: dict[str, Any], allowed: set[str], location: str) -> None:
    unknown = sorted(data.keys() - allowed)
    if unknown:
        raise ConfigError(f"{location}: claves desconocidas: {', '.join(unknown)}")


def _string(data: dict[str, Any], key: str, location: str, *, optional: bool = False) -> str | None:
    value = data.get(key)
    if value is None and optional:
        return None
    if not isinstance(value, str) or not value.strip():
        raise ConfigError(f"{location}.{key}: debe ser una cadena no vacía")
    return value.strip()


def _integer(value: Any, location: str, *, minimum: int = 0) -> int:
    if isinstance(value, bool) or not isinstance(value, int) or value < minimum:
        raise ConfigError(f"{location}: debe ser un entero >= {minimum}")
    return value


def _number(value: Any, location: str, *, minimum: float = 0) -> float:
    if isinstance(value, bool) or not isinstance(value, (int, float)) or value < minimum:
        raise ConfigError(f"{location}: debe ser un número >= {minimum}")
    return float(value)


def _boolean(value: Any, location: str) -> bool:
    if not isinstance(value, bool):
        raise ConfigError(f"{location}: debe ser booleano")
    return value


def _country(value: str | None, location: str) -> str | None:
    if value is None:
        return None
    normalized = value.upper()
    if len(normalized) != 2 or not normalized.isascii() or not normalized.isalpha():
        raise ConfigError(f"{location}: debe ser un código ISO-2")
    return normalized


def _filename(value: str | None, location: str) -> str | None:
    if value is None:
        return None
    if "\x00" in value:
        raise ConfigError(f"{location}: no puede contener un carácter nulo")
    # Validate both syntaxes so a config copied between Linux and Windows cannot
    # silently turn a file name into a nested or absolute path.
    posix = PurePosixPath(value)
    windows = PureWindowsPath(value)
    if (
        posix.is_absolute()
        or windows.is_absolute()
        or bool(windows.drive)
        or len(posix.parts) != 1
        or len(windows.parts) != 1
        or value in {".", ".."}
        or any(character in value for character in '<>:"|?*')
        or value.endswith((" ", "."))
    ):
        raise ConfigError(f"{location}: debe ser solo un nombre de archivo, sin directorios")
    reserved = value.split(".", 1)[0].casefold()
    if reserved in {"con", "prn", "aux", "nul"} or (
        len(reserved) == 4 and reserved[:3] in {"com", "lpt"} and reserved[3] in "123456789"
    ):
        raise ConfigError(f"{location}: nombre reservado por Windows: {value!r}")
    return value


def _validate_output_path(path: str | Path, location: str, *, directory: bool = False) -> Path:
    raw = str(path)
    if not raw.strip():
        raise ConfigError(f"{location}: la ruta no puede estar vacía")
    if "\x00" in raw:
        raise ConfigError(f"{location}: la ruta contiene un carácter nulo")
    try:
        resolved = Path(raw).expanduser()
        if not resolved.is_absolute():
            resolved = Path.cwd() / resolved
        resolved = resolved.resolve(strict=False)
    except (OSError, RuntimeError, ValueError) as exc:
        raise ConfigError(f"{location}: ruta inválida: {exc}") from exc

    candidate = resolved if directory else resolved.parent
    for parent in (candidate, *candidate.parents):
        if parent.exists() and not parent.is_dir():
            raise ConfigError(f"{location}: {parent} existe y no es un directorio")
    if directory and resolved.exists() and not resolved.is_dir():
        raise ConfigError(f"{location}: {resolved} existe y no es un directorio")
    if not directory and resolved.exists() and resolved.is_dir():
        raise ConfigError(f"{location}: {resolved} es un directorio, no un archivo")
    return resolved


def resolve_output_file(
    config: CliConfig,
    *,
    provider_codes: list[str] | None,
    kind: str,
    output_format: str,
    cli_value: str | None,
) -> str:
    """Resolve CLI-over-config output, relative to the process working directory."""

    if cli_value == "-":
        return "-"
    if cli_value is not None:
        return str(_validate_output_path(cli_value, "--output"))
    providers = selected_providers(config, provider_codes)
    if len(providers) != 1:
        raise ConfigError(
            "--output es obligatorio al ejecutar más de un proveedor; "
            "los nombres configurados son por proveedor"
        )
    provider = providers[0]
    filename = provider.plans_filename if kind == "plans" else provider.reviews_filename
    if filename is None:
        raise ConfigError(
            f"--output es obligatorio o debe configurar providers.{kind}_filename "
            f"para {provider.code!r}"
        )
    expected_suffix = f".{output_format}"
    if Path(filename).suffix.casefold() != expected_suffix:
        raise ConfigError(
            f"providers.{kind}_filename: debe terminar en {expected_suffix} "
            f"cuando --format={output_format}"
        )
    directory = config.output.directory or "."
    output_dir = _validate_output_path(directory, "output.directory", directory=True)
    return str(_validate_output_path(output_dir / filename, f"providers.{kind}_filename"))


def resolve_output_directory(config: CliConfig, cli_value: str | None) -> Path:
    value = cli_value or config.output.directory
    if value is None:
        raise ConfigError("--output-dir es obligatorio o debe configurar output.directory")
    return _validate_output_path(
        value,
        "--output-dir" if cli_value else "output.directory",
        directory=True,
    )


def _url(value: str, location: str) -> str:
    parsed = urlsplit(value)
    if parsed.scheme not in {"http", "https"} or not parsed.netloc or parsed.username:
        raise ConfigError(f"{location}: debe ser una URL HTTP/HTTPS sin credenciales")
    return value


def _source_list(value: Any, location: str) -> list[dict[str, Any]]:
    if value is None:
        return []
    if not isinstance(value, list):
        raise ConfigError(f"{location}: debe ser una lista de tablas")
    return [_table(item, f"{location}[{index}]") for index, item in enumerate(value)]


def _parse_plan_source(data: dict[str, Any], location: str) -> PlanSourceConfig:
    _reject_unknown(data, PLAN_SOURCE_KEYS, location)
    key = _string(data, "adapter_key", location)
    if key not in PLAN_ADAPTERS:
        raise ConfigError(f"{location}.adapter_key: adapter desconocido {key!r}")
    url = _url(_string(data, "url", location), f"{location}.url")
    raw_config = _table(data.get("config", {}), f"{location}.config")
    _reject_unknown(raw_config, PLAN_ADAPTER_CONFIG_KEYS[key], f"{location}.config")
    if key == "fixture_plans" and not isinstance(raw_config.get("fixture_plans"), list):
        raise ConfigError(f"{location}.config.fixture_plans: debe ser una lista")
    return PlanSourceConfig(
        name=_string(data, "name", location),
        adapter_key=key,
        url=url,
        enabled=_boolean(data.get("enabled", True), f"{location}.enabled"),
        timeout_seconds=(
            _integer(data["timeout_seconds"], f"{location}.timeout_seconds", minimum=1)
            if "timeout_seconds" in data
            else None
        ),
        retry_limit=_integer(data.get("retry_limit", 2), f"{location}.retry_limit"),
        config=dict(raw_config),
    )


def _parse_review_source(data: dict[str, Any], location: str) -> ReviewSourceConfig:
    _reject_unknown(data, REVIEW_SOURCE_KEYS, location)
    key = _string(data, "adapter_key", location)
    if key not in REVIEW_ADAPTERS:
        raise ConfigError(f"{location}.adapter_key: adapter desconocido {key!r}")
    url = _url(_string(data, "url", location), f"{location}.url")
    raw_config = dict(_table(data.get("config", {}), f"{location}.config"))
    _reject_unknown(raw_config, REVIEW_ADAPTER_CONFIG_KEYS[key], f"{location}.config")
    source = ReviewSourceConfig(
        name=_string(data, "name", location),
        adapter_key=key,
        url=url,
        platform=_string(data, "platform", location),
        app_id=_string(data, "app_id", location, optional=True),
        country_code=_country(
            _string(data, "country_code", location, optional=True),
            f"{location}.country_code",
        ),
        enabled=_boolean(data.get("enabled", True), f"{location}.enabled"),
        timeout_seconds=(
            _integer(data["timeout_seconds"], f"{location}.timeout_seconds", minimum=1)
            if "timeout_seconds" in data
            else None
        ),
        retry_limit=_integer(data.get("retry_limit", 2), f"{location}.retry_limit"),
        request_delay_seconds=_number(
            data.get("request_delay_seconds", 0), f"{location}.request_delay_seconds"
        ),
        max_pages=_integer(data.get("max_pages", 20), f"{location}.max_pages", minimum=1),
        config=raw_config,
    )
    # Adapter-specific validation is part of config validation, before scraping.
    try:
        get_review_adapter(key).validate_config(
            ReviewSourceDTO(
                id=None,
                provider_code="validation",
                platform=source.platform,
                source_url=source.url,
                external_entity_id=source.app_id,
                country_code=source.country_code,
                adapter_config=source.config,
            )
        )
    except Exception as exc:
        raise ConfigError(f"{location}.config: {exc}") from exc
    return source


def load_config(path: str | Path) -> CliConfig:
    config_path = Path(path)
    try:
        with config_path.open("rb") as stream:
            root = tomllib.load(stream)
    except (OSError, tomllib.TOMLDecodeError) as exc:
        raise ConfigError(f"{config_path}: no se pudo leer TOML: {exc}") from exc
    _reject_unknown(root, {"defaults", "output", "providers"}, "config")
    defaults_data = _table(root.get("defaults", {}), "defaults")
    _reject_unknown(defaults_data, DEFAULT_KEYS, "defaults")
    defaults = Defaults(
        timeout_seconds=_integer(
            defaults_data.get("timeout_seconds", 20), "defaults.timeout_seconds", minimum=1
        ),
        max_items=_integer(defaults_data.get("max_items", 100), "defaults.max_items", minimum=1),
        country_code=_country(
            _string(defaults_data, "country_code", "defaults", optional=True),
            "defaults.country_code",
        ),
        user_agent=_string(
            defaults_data or {"user_agent": "MarketMonitorCLI/1.0"},
            "user_agent",
            "defaults",
        )
        if "user_agent" in defaults_data
        else "MarketMonitorCLI/1.0",
        max_response_bytes=_integer(
            defaults_data.get("max_response_bytes", 5_000_000),
            "defaults.max_response_bytes",
            minimum=1,
        ),
        allow_private_hosts=_boolean(
            defaults_data.get("allow_private_hosts", False), "defaults.allow_private_hosts"
        ),
    )
    output_data = _table(root.get("output", {}), "output")
    _reject_unknown(output_data, OUTPUT_KEYS, "output")
    output = OutputConfig(
        directory=_string(output_data, "directory", "output", optional=True),
    )
    provider_rows = _source_list(root.get("providers"), "providers")
    if not provider_rows:
        raise ConfigError("providers: se requiere al menos un proveedor")
    providers: list[ProviderConfig] = []
    seen: set[str] = set()
    for index, row in enumerate(provider_rows):
        location = f"providers[{index}]"
        _reject_unknown(row, PROVIDER_KEYS, location)
        code = _string(row, "code", location)
        if code in seen:
            raise ConfigError(f"{location}.code: código duplicado {code!r}")
        seen.add(code)
        plans = tuple(
            _parse_plan_source(item, f"{location}.plan_sources[{source_index}]")
            for source_index, item in enumerate(
                _source_list(row.get("plan_sources"), f"{location}.plan_sources")
            )
        )
        reviews = tuple(
            _parse_review_source(item, f"{location}.review_sources[{source_index}]")
            for source_index, item in enumerate(
                _source_list(row.get("review_sources"), f"{location}.review_sources")
            )
        )
        providers.append(
            ProviderConfig(
                code=code,
                name=_string(row, "name", location),
                plan_sources=plans,
                review_sources=reviews,
                plans_filename=_filename(
                    _string(row, "plans_filename", location, optional=True),
                    f"{location}.plans_filename",
                ),
                reviews_filename=_filename(
                    _string(row, "reviews_filename", location, optional=True),
                    f"{location}.reviews_filename",
                ),
            )
        )
    return CliConfig(defaults=defaults, providers=tuple(providers), output=output)


def selected_providers(config: CliConfig, codes: list[str] | None) -> tuple[ProviderConfig, ...]:
    if not codes:
        return config.providers
    requested = set(codes)
    found = tuple(provider for provider in config.providers if provider.code in requested)
    missing = sorted(requested - {provider.code for provider in found})
    if missing:
        raise ConfigError(f"--provider: proveedor inexistente: {', '.join(missing)}")
    return found
