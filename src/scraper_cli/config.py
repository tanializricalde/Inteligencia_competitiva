class ConfigError(ValueError):
    """Configuration error with a human-readable field location."""


@dataclass(frozen=True, slots=True)
class Defaults:
    timeout_seconds: int = 20
    max_items: int = 100
    country_code: str | None = None
    user_agent: str = "MarketMonitorCLI/1.0"
    max_response_bytes: int = 5_000_000
    allow_private_hosts: bool = False


@dataclass(frozen=True, slots=True)
class OutputConfig:
    """Optional defaults for files generated by the CLI."""

    directory: str | None = None


@dataclass(frozen=True, slots=True)
class PlanSourceConfig:
    name: str
    adapter_key: str
    url: str
    enabled: bool = True
    timeout_seconds: int | None = None
    retry_limit: int = 2
    config: dict[str, Any] = field(default_factory=dict)


@dataclass(frozen=True, slots=True)
class ReviewSourceConfig:
    name: str
    adapter_key: str
    url: str
    platform: str
    app_id: str | None = None
    country_code: str | None = None
    enabled: bool = True
    timeout_seconds: int | None = None
    retry_limit: int = 2
    request_delay_seconds: float = 0
    max_pages: int = 20
    config: dict[str, Any] = field(default_factory=dict)


@dataclass(frozen=True, slots=True)
class ProviderConfig:
    code: str
    name: str
    plan_sources: tuple[PlanSourceConfig, ...] = ()
    review_sources: tuple[ReviewSourceConfig, ...] = ()
    plans_filename: str | None = None
    reviews_filename: str | None = None


@dataclass(frozen=True, slots=True)
class CliConfig:
    defaults: Defaults
    providers: tuple[ProviderConfig, ...]
    output: OutputConfig = OutputConfig()


